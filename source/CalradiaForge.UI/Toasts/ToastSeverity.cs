namespace CalradiaForge.UI.Toasts {

	/// <summary>
	/// Visual severity level for toast notifications.
	/// Controls accent color and icon selection.
	/// </summary>
	public enum ToastSeverity {
		/// <summary>
		/// Informational notification.
		/// </summary>
		Info,
		/// <summary>
		/// Success notification.
		/// </summary>
		Success,
		/// <summary>
		/// Warning notification.
		/// </summary>
		Warning,
		/// <summary>
		/// Error notification.
		/// </summary>
		Error
	}
}
